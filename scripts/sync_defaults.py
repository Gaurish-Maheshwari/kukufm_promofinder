#!/usr/bin/env python3
"""Regenerate promo_engine/defaults.py from config/*.yaml.

The YAML files are the source of truth you edit. defaults.py is a frozen copy baked
into the package so the engine still runs if the config folder is missing, unreadable
or corrupt (e.g. a serverless bundle that forgot to include it). A test fails if the two
drift apart: run this script after editing the YAML.
"""
import pprint
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
cfg = yaml.safe_load((ROOT / "config" / "default.yaml").read_text(encoding="utf-8"))
lex = yaml.safe_load((ROOT / "config" / "lexicons.yaml").read_text(encoding="utf-8"))
out = ROOT / "promo_engine" / "defaults.py"
out.write_text(
    '"""AUTO-GENERATED by scripts/sync_defaults.py: a frozen copy of config/default.yaml and\n'
    'config/lexicons.yaml used only when those files cannot be read. Do not edit by hand."""\n\n'
    f"DEFAULT_CONFIG = {pprint.pformat(cfg, width=110, sort_dicts=False)}\n\n"
    f"DEFAULT_LEXICONS = {pprint.pformat(lex, width=110, sort_dicts=False)}\n",
    encoding="utf-8",
)
print(f"wrote {out}")
